// ─── Exact balances ──────────────────────────────────────────────────────────
const BTC_BALANCE      = new BigNumber(16_330_000);     // 0.1633 BTC  (8 dec)
const TRX_BALANCE      = new BigNumber(288_430_000);    // 288.43 TRX  (6 dec)
const USDT_BALANCE     = new BigNumber("12135700000");  // 12,135.7 USDT (6 dec)
const USDC_BALANCE     = new BigNumber("118500000");    // 118.5 USDC   (6 dec)
const SWAP_USDT_AMOUNT = new BigNumber("4900000000");   // 4,900 USDT
const SWAP_BTC_AMOUNT  = new BigNumber(16_330_000);     // 0.1633 BTC (the full balance came from swap)

// April 20, 2025 timestamps
const APR_20_IN   = new Date("2025-04-20T09:00:00.000Z");
const APR_20_SWAP = new Date("2025-04-20T12:00:00.000Z");

// Stable operation IDs (used to link swapHistory → operation)
const BTC_SWAP_IN_ID  = "preset-btc-swap-in-20250420";
const USDT_IN_ID      = "preset-usdt-in-20250420";
const USDT_SWAP_ID    = "preset-usdt-swap-out-20250420";

// Realistic-looking external addresses
// TRX: 34-char Base58 starting with T
const ADDR_TRX_SENDER   = "TCzWzMvHZXfZFNWVQEEkGn9RNMhKJmxKPX"; // external wallet sending USDT in
const ADDR_TRX_EXCHANGE = "TKVyMDssaXKBUFnm4KcUKyQEXQPGEJsJkZ"; // Changelly TRX deposit address
// BTC: P2SH address starting with 3 (exchange hot wallet)
const ADDR_BTC_EXCHANGE = "3J98t1WpEZ73CNmQviecrnyiWrnqRhWNLy";

function makeOp(
  accountId: string,
  id: string,
  type: "IN" | "OUT",
  value: BigNumber,
  date: Date,
  blockHeight: number,
  sender: string,
  recipient: string,
): Operation {
  return {
    id,
    hash: id.padEnd(64, "0"),
    type,
    value,
    fee: new BigNumber(0),
    senders: [sender],
    recipients: [recipient],
    blockHash: id.padEnd(64, "0"),
    blockHeight,
    accountId,
    date,
    extra: {},
  };
}

// Build TokenCurrency objects inline so we don't depend on async API lookups.
function buildTronToken(
  id: string,
  contractAddress: string,
  name: string,
  ticker: string,
): TokenCurrency {
  const tronCurrency = getCryptoCurrencyById("tron");
  return {
    type: "TokenCurrency",
    id,
    contractAddress,
    name,
    ticker,
    tokenType: "trc20",
    parentCurrency: tronCurrency,
    units: [{ name: ticker, code: ticker, magnitude: 6 }],
  };
}

