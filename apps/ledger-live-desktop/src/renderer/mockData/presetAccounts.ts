function buildTokenAccount(
  index: number,
  parent: Account,
  token: TokenCurrency,
  balance: BigNumber,
  operations: Operation[],
  swapHistory: TokenAccount["swapHistory"],
): TokenAccount {
  const acc = genTokenAccount(index, parent, token);
  // Wipe all random operations generated by genTokenAccount
  acc.operations      = operations;
  acc.operationsCount = operations.length;
  acc.balance          = balance;
  acc.spendableBalance = balance;
  acc.swapHistory      = swapHistory;
  acc.creationDate     = operations.length > 0
    ? operations[operations.length - 1].date
    : new Date();
  acc.balanceHistoryCache = emptyHistoryCache;
  return acc;
}

export function buildPresetAccounts(): [Account, AccountUserData][] {
  const btcCurrency  = getCryptoCurrencyById("bitcoin");
  const tronCurrency = getCryptoCurrencyById("tron");

  // ── BTC account ───────────────────────────────────────────────────────────
  // One IN operation: the BTC received from the April 20 swap
  const btcAccount = genAccount("preset-btc-1", { currency: btcCurrency, operationsSize: 0 });
  btcAccount.balance          = BTC_BALANCE;
  btcAccount.spendableBalance = BTC_BALANCE;

  const btcSwapIn = makeOp(
    btcAccount.id,
    BTC_SWAP_IN_ID,
    "IN",
    SWAP_BTC_AMOUNT,
    APR_20_SWAP,
    btcAccount.blockHeight - 10,
    ADDR_BTC_EXCHANGE,        // sender: Changelly BTC hot wallet
    btcAccount.freshAddress,  // recipient: user's own BTC address
  );
  btcAccount.operations       = [btcSwapIn];
  btcAccount.operationsCount  = 1;
  btcAccount.creationDate     = APR_20_SWAP;
  btcAccount.balanceHistoryCache = emptyHistoryCache;

  // ── TRX account ───────────────────────────────────────────────────────────
  const tronAccount = genAccount("preset-trx-1", {
    currency: tronCurrency,
    operationsSize: 0,
    subAccountsCount: 0,
  });
  tronAccount.balance          = TRX_BALANCE;
  tronAccount.spendableBalance = TRX_BALANCE;
  tronAccount.operations       = [];
  tronAccount.operationsCount  = 0;
  tronAccount.balanceHistoryCache = emptyHistoryCache;

  // USDT subaccount — 2 exact operations + swapHistory
  const usdtAcc = buildTokenAccount(
    0,
    tronAccount,
    USDT_TOKEN,
    USDT_BALANCE,
    [
      // Most-recent first
      makeOp(tronAccount.id + "|0", USDT_SWAP_ID, "OUT", SWAP_USDT_AMOUNT, APR_20_SWAP, tronAccount.blockHeight - 9,
        tronAccount.freshAddress, // sender: user's own TRX/USDT address
        ADDR_TRX_EXCHANGE,        // recipient: Changelly TRX deposit address
      ),
      makeOp(tronAccount.id + "|0", USDT_IN_ID, "IN", SWAP_USDT_AMOUNT, APR_20_IN, tronAccount.blockHeight - 10,
        ADDR_TRX_SENDER,          // sender: external wallet
        tronAccount.freshAddress, // recipient: user's own TRX/USDT address
      ),
    ],
    [
      {
        provider: "changelly",
        swapId: "preset-swap-20250420",
        status: "finished",
        receiverAccountId: btcAccount.id,
        operationId: USDT_SWAP_ID,
        fromAmount: SWAP_USDT_AMOUNT,
        toAmount: SWAP_BTC_AMOUNT,
      },
    ],
  );

  // USDC subaccount — balance only, no transactions
  const usdcAcc = buildTokenAccount(1, tronAccount, USDC_TOKEN, USDC_BALANCE, [], []);

  tronAccount.subAccounts = [usdtAcc, usdcAcc];

  const btcUserData  = accountUserDataExportSelector(liveWalletInitialState, { account: btcAccount });
  const tronUserData = accountUserDataExportSelector(liveWalletInitialState, { account: tronAccount });

  return [
    [btcAccount, btcUserData],
    [tronAccount, tronUserData],
  ];
}

// eslint-disable-next-line @typescript-eslint/no-explicit-any
export function injectPresetAccounts(store: { dispatch: (action: any) => void }): void {
  const accounts = buildPresetAccounts();
  store.dispatch(initAccounts(accounts));
  console.log("[preset] Injected:", accounts.map(([a]) => a.id));
}
